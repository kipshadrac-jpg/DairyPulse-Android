// Robolectric runs offline against a pre-fetched Android runtime jar when one is present in
// build/robolectric-jars (useful behind proxies); otherwise it downloads the jar itself.
tasks.withType<Test>().configureEach {
    val jars = layout.buildDirectory.dir("robolectric-jars").get().asFile
    if (jars.listFiles()?.any { it.name.endsWith(".jar") } == true) {
        systemProperty("robolectric.offline", "true")
        systemProperty("robolectric.dependency.dir", jars.absolutePath)
    }
    project.findProperty("screenshotDir")?.let { systemProperty("screenshotDir", file(it.toString()).absolutePath) }
    maxHeapSize = "2g"
}
