package com.dairypulse.app.ui.money

import android.content.Context
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.net.Uri
import androidx.core.content.FileProvider
import com.dairypulse.app.data.FarmSettings
import com.dairypulse.app.domain.ProfitAndLoss
import com.dairypulse.app.ui.common.money
import com.dairypulse.app.ui.common.num
import com.dairypulse.app.ui.common.rate
import com.dairypulse.app.ui.common.pretty
import java.io.File
import java.time.LocalDateTime
import java.time.format.DateTimeFormatter

/** Draws a one-page A4 P&L statement with Android's built-in PDF support (no internet needed). */
object PdfExporter {
    private const val W = 595
    private const val H = 842
    private const val M = 48f

    fun export(context: Context, settings: FarmSettings, pnl: ProfitAndLoss, periodLabel: String): Uri {
        val doc = PdfDocument()
        val page = doc.startPage(PdfDocument.PageInfo.Builder(W, H, 1).create())
        val c = page.canvas
        val cur = settings.currency

        val green = Color.rgb(0x1B, 0x5E, 0x20)
        val red = Color.rgb(0xC6, 0x28, 0x28)
        val title = Paint().apply { textSize = 22f; typeface = Typeface.DEFAULT_BOLD; color = Color.WHITE; isAntiAlias = true }
        val sub = Paint().apply { textSize = 11f; color = Color.WHITE; isAntiAlias = true }
        val body = Paint().apply { textSize = 12f; color = Color.DKGRAY; isAntiAlias = true }
        val bold = Paint(body).apply { typeface = Typeface.DEFAULT_BOLD; color = Color.BLACK }
        val right = Paint(body).apply { textAlign = Paint.Align.RIGHT }
        val rule = Paint().apply { color = Color.LTGRAY; strokeWidth = 1f }

        // Header band
        c.drawRect(0f, 0f, W.toFloat(), 96f, Paint().apply { color = green })
        c.drawText(settings.farmName, M, 44f, title)
        c.drawText("Profit & Loss Statement – $periodLabel (${pnl.from.pretty()} to ${pnl.to.pretty()})", M, 70f, sub)

        var y = 136f
        fun row(label: String, value: String, labelPaint: Paint = body, valueColor: Int = Color.DKGRAY, valueBold: Boolean = false) {
            c.drawText(label, M, y, labelPaint)
            c.drawText(value, W - M, y, Paint(right).apply {
                color = valueColor; if (valueBold) typeface = Typeface.DEFAULT_BOLD
            })
            y += 22f
        }
        fun divider() { c.drawLine(M, y - 14f, W - M, y - 14f, rule); y += 6f }

        c.drawText("Summary", M, y, bold); y += 24f
        row("Milk produced", "${num(pnl.milkProduced)} L")
        if (pnl.milkToCalves > 0) {
            row("Fed to calves", "${num(pnl.milkToCalves)} L")
            row("Milk sold", "${num(pnl.milkLiters)} L")
        }
        row("Net profit", money(cur, pnl.netProfit), valueColor = if (pnl.netProfit < 0) red else green, valueBold = true)
        row("Profit margin", "${num(pnl.marginPct)} %")
        row("Profit per litre", rate(cur, pnl.profitPerLiter))
        y += 16f

        c.drawText("Breakdown", M, y, bold); y += 24f
        row("Gross milk sales", money(cur, pnl.milkSales))
        pnl.otherIncome.forEach { row(it.label, money(cur, it.amount)) }
        row("Total revenue", money(cur, pnl.totalRevenue), bold, Color.BLACK, true)
        divider()
        row("Feed expenses", "- " + money(cur, pnl.feedCost), valueColor = red)
        pnl.expenses.forEach { row(it.label, "- " + money(cur, it.amount), valueColor = red) }
        row("Total expenses", "- " + money(cur, pnl.totalExpenses), bold, red, true)
        divider()
        row("NET FARM PROFIT", money(cur, pnl.netProfit), bold, if (pnl.netProfit < 0) red else green, true)

        val stamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("d MMM yyyy, HH:mm"))
        c.drawText("Generated by DairyDesk on $stamp. Figures are from the farm's own records.", M, H - 40f,
            Paint(body).apply { textSize = 9f; color = Color.GRAY })

        doc.finishPage(page)
        val dir = File(context.cacheDir, "reports").apply { mkdirs() }
        val safeName = settings.farmName.replace(Regex("[^A-Za-z0-9]+"), "_").trim('_').ifEmpty { "Farm" }
        val file = File(dir, "${safeName}_PnL_${pnl.from}_to_${pnl.to}.pdf")
        file.outputStream().use { doc.writeTo(it) }
        doc.close()
        return FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
    }
}
